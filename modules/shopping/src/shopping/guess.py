BY_WORD: dict[str, str] = {
    fold(word): category for category, words in WORDS.items() for word in words
}
BY_PHRASE: dict[str, str] = {fold(phrase): category for phrase, category in PHRASES.items()}


def _forms(word: str) -> tuple[str, ...]:
    forms = [word]
    if word.endswith("es") and len(word) > 4:
        forms.append(word[:-2])
    if word.endswith("s") and len(word) > 3:
        forms.append(word[:-1])
    return tuple(forms)


def category(name: str) -> str:
    folded = fold(name)
    padded = f" {folded} "
    for phrase in sorted(BY_PHRASE, key=len, reverse=True):
        if f" {phrase} " in padded:
            return BY_PHRASE[phrase]
    for word in folded.split():
        for form in _forms(word):
            if form in BY_WORD:
                return BY_WORD[form]
    return OTHER
