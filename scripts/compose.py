"""Generate docker-compose.yml from openarga.yaml and the module manifests.

uv run python scripts/compose.py            writes docker-compose.yml
uv run python scripts/compose.py --check    fails if docker-compose.yml is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# Generated by scripts/compose.py from openarga.yaml. Edit that file, not this one.\n"
AUTH_PROVIDERS = {"local", "google", "oidc"}
DEFAULTS = {
    "locale": "OPENARGA_LOCALE",
    "timezone": "OPENARGA_TIMEZONE",
    "currency": "OPENARGA_CURRENCY",
    "country": "OPENARGA_COUNTRY",
    "region": "OPENARGA_REGION",
    "area": "OPENARGA_AREA",
}
AI = {
    "provider": "OPENARGA_AI_PROVIDER",
    "base_url": "OPENARGA_AI_BASE_URL",
    "fast_model": "OPENARGA_AI_FAST_MODEL",
    "smart_model": "OPENARGA_AI_SMART_MODEL",
    "monthly_tokens": "OPENARGA_AI_MONTHLY_TOKENS",
}
HEALTHY = {"condition": "service_healthy"}
DONE = {"condition": "service_completed_successfully"}


class InvalidConfig(ValueError):
    pass


class Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data: Any) -> bool:
        return True


def config_path(root: Path) -> Path:
    own = root / "openarga.yaml"
    return own if own.exists() else root / "openarga.example.yaml"


def module_folders(root: Path) -> dict[str, str]:
    found = {}
    manifests = [*(root / "modules").glob("*/manifest.yaml")]
    manifests += (root / "modules" / "custom").glob("*/manifest.yaml")
    for manifest in manifests:
        folder = manifest.parent
        if folder.name.startswith("_") or not (folder / "Dockerfile").exists():
            continue
        module_id = yaml.safe_load(manifest.read_text(encoding="utf-8"))["id"]
        found[module_id] = folder.relative_to(root).as_posix()
    return dict(sorted(found.items()))


def available_modules(root: Path) -> list[str]:
    return list(module_folders(root))


def enabled_modules(config: dict[str, Any], available: list[str]) -> list[str]:
    section = config.get("modules") or {}
    chosen = section.get("enabled", "all")
    disabled = set(section.get("disabled") or [])
    wanted = available if chosen == "all" else list(chosen)
    unknown = sorted((set(wanted) | disabled) - set(available))
    if unknown:
        raise InvalidConfig(f"unknown modules in openarga.yaml: {', '.join(unknown)}")
    return [module for module in available if module in wanted and module not in disabled]


def instance_environment(config: dict[str, Any]) -> dict[str, str]:
    environment = {"PUBLIC_URL": public_url(config)}
    for section, names in (("defaults", DEFAULTS), ("ai", AI)):
        values = config.get(section) or {}
        for key, name in names.items():
            if values.get(key) not in (None, ""):
                environment[name] = str(values[key])
    environment["OPENARGA_AI_KEY"] = "${OPENARGA_AI_KEY:-}"
    environment["CONNECTIONS_MODE"] = str(config.get("connections", "live"))
    if config.get("demo"):
        environment["OPENARGA_DEMO"] = "true"
    return environment


def public_url(config: dict[str, Any]) -> str:
    domain = config.get("domain") or "localhost"
    if domain == "localhost":
        return "http://localhost:8000"
    return f"https://{domain}"


def providers(config: dict[str, Any]) -> list[str]:
    chosen = list((config.get("auth") or {}).get("providers") or ["local"])
    unknown = sorted(set(chosen) - AUTH_PROVIDERS)
    if unknown:
        raise InvalidConfig(f"unknown auth providers in openarga.yaml: {', '.join(unknown)}")
    return chosen


def database_url(user: str, password: str) -> str:
    return f"postgresql+asyncpg://{user}:${{{password}}}@postgres:5432/${{POSTGRES_DB}}"


def module_service(module_id: str, folder: str, instance: dict[str, str]) -> dict[str, Any]:
    return {
        "image": f"openarga/{module_id}:local",
        "build": {"context": ".", "dockerfile": f"{folder}/Dockerfile"},
        "environment": {
            "DATABASE_URL": database_url(f"svc_{module_id}", f"{module_id.upper()}_DB_PASSWORD"),
            "KERNEL_URL": "http://kernel:8000",
            "MODULE_REGISTRATION_TOKEN": "${MODULE_REGISTRATION_TOKEN}",
            **instance,
        },
        "depends_on": {"kernel": HEALTHY},
        "restart": "unless-stopped",
    }


MODULE_KEYS = {"hub": ["HUB_CREDENTIALS_KEY"]}
CALLS_AI = {"hub"}
HOST_GATEWAY = ["host.docker.internal:host-gateway"]


def configure_module_service(module_id: str, service: dict[str, Any]) -> None:
    for name in MODULE_KEYS.get(module_id, []):
        service["environment"][name] = f"${{{name}}}"
    if module_id in CALLS_AI:
        service["extra_hosts"] = list(HOST_GATEWAY)


def worker_service(module_id: str, folder: str, instance: dict[str, str]) -> dict[str, Any]:
    service = module_service(module_id, folder, instance)
    del service["build"]
    service["pull_policy"] = "never"
    service["command"] = ["python", "-m", f"{module_id}.publisher"]
    service["depends_on"] = {module_id: HEALTHY}
    service["healthcheck"] = {"disable": True}
    return service


def has_worker(root: Path, folder: str, module_id: str) -> bool:
    return (root / folder / "src" / module_id / "publisher.py").exists()


def auth_sync_environment(chosen: list[str]) -> dict[str, str]:
    environment = {
        "KC_ADMIN_PASSWORD": "${KC_ADMIN_PASSWORD}",
        "ARGA_WEB_CLIENT_SECRET": "${ARGA_WEB_CLIENT_SECRET}",
        "PUBLIC_URL": "${PUBLIC_URL}",
    }
    if "local" in chosen:
        environment["OPENARGA_ADMIN_USERNAME"] = "${OPENARGA_ADMIN_USERNAME:-admin}"
        environment["OPENARGA_ADMIN_PASSWORD"] = "${OPENARGA_ADMIN_PASSWORD}"
    if "google" in chosen:
        environment["GOOGLE_CLIENT_ID"] = "${GOOGLE_CLIENT_ID}"
        environment["GOOGLE_CLIENT_SECRET"] = "${GOOGLE_CLIENT_SECRET}"
    if "oidc" in chosen:
        for name in ("ISSUER", "CLIENT_ID", "CLIENT_SECRET", "NAME"):
            environment[f"OPENARGA_OIDC_{name}"] = f"${{OPENARGA_OIDC_{name}}}"
    return environment


def generate(config: dict[str, Any], root: Path = ROOT) -> dict[str, Any]:
    folders = module_folders(root)
    modules = enabled_modules(config, list(folders))
    chosen = providers(config)
    instance = instance_environment(config)
    sync = auth_sync_environment(chosen)
    sync["PUBLIC_URL"] = instance["PUBLIC_URL"]

    roles_environment = {
        "ADMIN_DATABASE_URL": database_url("${POSTGRES_USER}", "POSTGRES_PASSWORD"),
        "KERNEL_DB_PASSWORD": "${KERNEL_DB_PASSWORD}",
        "AUTH_DB_PASSWORD": "${AUTH_DB_PASSWORD}",
    }
    for module_id in modules:
        variable = f"{module_id.upper()}_DB_PASSWORD"
        roles_environment[variable] = f"${{{variable}}}"

    services: dict[str, Any] = {
        "postgres": {
            "image": "postgres:16-alpine",
            "environment": {
                "POSTGRES_DB": "${POSTGRES_DB}",
                "POSTGRES_USER": "${POSTGRES_USER}",
                "POSTGRES_PASSWORD": "${POSTGRES_PASSWORD}",
            },
            "volumes": ["pgdata:/var/lib/postgresql/data"],
            "healthcheck": {
                "test": ["CMD-SHELL", "pg_isready -U ${POSTGRES_USER}"],
                "interval": "5s",
                "retries": 10,
            },
            "restart": "unless-stopped",
        },
        "roles": {
            "image": "openarga/kernel:local",
            "pull_policy": "never",
            "command": ["python", "-m", "kernel.roles"],
            "environment": roles_environment,
            "depends_on": {"postgres": HEALTHY},
            "healthcheck": {"disable": True},
        },
        "kernel": {
            "image": "openarga/kernel:local",
            "build": {"context": ".", "dockerfile": "kernel/Dockerfile"},
            "environment": {
                "DATABASE_URL": database_url("arga_kernel", "KERNEL_DB_PASSWORD"),
                "MODULE_REGISTRATION_TOKEN": "${MODULE_REGISTRATION_TOKEN}",
                **instance,
            },
            "depends_on": {"roles": DONE},
            "restart": "unless-stopped",
        },
        "auth": {
            "image": "openarga/auth:local",
            "build": {"context": ".", "dockerfile": "auth/Dockerfile"},
            "environment": {
                "PUBLIC_URL": instance["PUBLIC_URL"],
                "KC_DB_URL": "jdbc:postgresql://postgres:5432/${POSTGRES_DB}",
                "KC_DB_USERNAME": "arga_auth",
                "KC_DB_PASSWORD": "${AUTH_DB_PASSWORD}",
                "KC_DB_SCHEMA": "auth",
                "KC_HTTP_ENABLED": "true",
                "KC_PROXY_HEADERS": "xforwarded",
                "KC_HOSTNAME": instance["PUBLIC_URL"] + "/auth",
                "KC_BOOTSTRAP_ADMIN_USERNAME": "admin",
                "KC_BOOTSTRAP_ADMIN_PASSWORD": "${KC_ADMIN_PASSWORD}",
            },
            "depends_on": {"roles": DONE},
            "restart": "unless-stopped",
        },
        "auth-sync": {
            "image": "openarga/auth:local",
            "pull_policy": "never",
            "entrypoint": ["/bin/bash", "/opt/arga/sync.sh"],
            "command": [],
            "environment": sync,
            "depends_on": {"auth": HEALTHY},
            "healthcheck": {"disable": True},
        },
        "mcp": {
            "image": "openarga/mcp:local",
            "build": {"context": ".", "dockerfile": "mcp/Dockerfile"},
            "environment": {
                "KERNEL_URL": "http://kernel:8000",
                "MCP_ALLOWED_SCOPES": "${MCP_ALLOWED_SCOPES:-}",
                **{key: value for key, value in instance.items() if key == "OPENARGA_DEMO"},
            },
            "depends_on": {"kernel": HEALTHY},
            "restart": "unless-stopped",
        },
        "shell": {
            "image": "openarga/shell:local",
            "build": {"context": ".", "dockerfile": "shell/Dockerfile"},
            "environment": {"KERNEL_URL": "http://kernel:8000", **instance},
            "depends_on": {"kernel": HEALTHY},
            "restart": "unless-stopped",
        },
        "gateway": {
            "image": "openarga/gateway:local",
            "build": {"context": ".", "dockerfile": "gateway/Dockerfile"},
            "environment": {
                "KERNEL_URL": "http://kernel:8000",
                "SHELL_URL": "http://shell:3000",
                "MCP_URL": "http://mcp:8000",
                "AUTH_URL": "http://auth:8080",
                "SESSION_SECRET": "${SESSION_SECRET}",
                "OAUTH_ISSUER": instance["PUBLIC_URL"] + "/auth/realms/arga",
                "OAUTH_JWKS_URL": "http://auth:8080/auth/realms/arga/protocol/openid-connect/certs",
                "MCP_RESOURCE_URL": instance["PUBLIC_URL"] + "/mcp",
                "OIDC_INTERNAL_URL": "http://auth:8080/auth/realms/arga",
                "OIDC_CLIENT_ID": "arga-web",
                "OIDC_CLIENT_SECRET": "${ARGA_WEB_CLIENT_SECRET}",
                **instance,
            },
            "depends_on": {
                "kernel": HEALTHY,
                "shell": HEALTHY,
                "mcp": HEALTHY,
                "auth-sync": DONE,
            },
            "ports": ["8000:8000"],
            "restart": "unless-stopped",
        },
    }
    for module_id in modules:
        folder = folders[module_id]
        services[module_id] = module_service(module_id, folder, instance)
        configure_module_service(module_id, services[module_id])
        if has_worker(root, folder, module_id):
            services[f"{module_id}-worker"] = worker_service(module_id, folder, instance)
    return {"name": "openarga", "services": services, "volumes": {"pgdata": {}}}


def render(compose: dict[str, Any]) -> str:
    return HEADER + yaml.dump(
        compose, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=120
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, default=None)
    parser.add_argument("--output", type=Path, default=ROOT / "docker-compose.yml")
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)
    source = arguments.config or config_path(ROOT)
    try:
        text = render(generate(yaml.safe_load(source.read_text(encoding="utf-8")) or {}))
    except InvalidConfig as error:
        print(error, file=sys.stderr)
        return 2
    if arguments.check:
        current = arguments.output.read_text(encoding="utf-8") if arguments.output.exists() else ""
        if current != text:
            print(f"{arguments.output.name} is stale: run scripts/compose.py", file=sys.stderr)
            return 1
        return 0
    arguments.output.write_text(text, encoding="utf-8")
    print(f"wrote {arguments.output.name} from {source.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
